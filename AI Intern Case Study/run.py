#!/usr/bin/env python3
"""RouteSentry CLI entrypoint.

Usage:
    python3 run.py                           # ML-driven (default, primary)
    python3 run.py --mode rule_based         # original deterministic rule, preserved unchanged
    python3 run.py --mode ml --recalibrate   # re-run the threshold calibration grid search first

Both modes write the exact same output contract (see sample_output_format_v2.csv)
via the same routesentry.pipeline CSV writers -- only the statistical-signal
step differs. See docs/model_selection.md for why ML is now the default, and
docs/ml_driven_pipeline.md for the full design.

Deterministic: no network calls, no LLM calls. Both modes use a fixed random
seed (ml.config.RANDOM_SEED) and produce byte-identical output across runs
(see docs/reproducibility_report.md for --mode rule_based, and
docs/ml_driven_reproducibility_report.md for the default --mode ml -- both
generated by scripts/check_reproducibility.py).
"""
from __future__ import annotations

import argparse
import logging
import sys
import time
from pathlib import Path

from routesentry import config as rule_config
from routesentry.pipeline import run as run_rule_based
from routesentry.pipeline import write_evidence_ledger_csv, write_output_csv

DEFAULT_DIR = Path(__file__).resolve().parent


def main() -> int:
    parser = argparse.ArgumentParser(description="RouteSentry -- freight cost anomaly detection")
    parser.add_argument("--shipments", default=str(DEFAULT_DIR / "shipment_records.csv"))
    parser.add_argument("--notes", default=str(DEFAULT_DIR / "context_notes.csv"))
    parser.add_argument("--output", default=str(DEFAULT_DIR / "submission" / "output.csv"))
    parser.add_argument("--ledger", default=str(DEFAULT_DIR / "submission" / "evidence_ledger.csv"))
    parser.add_argument(
        "--mode", choices=["ml", "rule_based"], default="ml",
        help="ml (default): calibrated LOF-driven anomaly flag. "
             "rule_based: the original flat +15pp threshold rule, preserved unchanged.",
    )
    parser.add_argument("--threshold", type=float, default=rule_config.RISE_THRESHOLD_PCT,
                         help="(--mode rule_based only) flat anomaly threshold in percentage points (default: %(default)s)")
    parser.add_argument("--recalibrate", action="store_true",
                         help="(--mode ml only) re-run the train/validation contamination grid search instead of using the stored calibrated value")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args()

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)-7s %(name)s: %(message)s",
    )
    logger = logging.getLogger("routesentry.run")

    Path(args.output).parent.mkdir(parents=True, exist_ok=True)

    t0 = time.monotonic()
    try:
        if args.mode == "rule_based":
            ledger = run_rule_based(args.shipments, args.notes, threshold=args.threshold)
        else:
            from ml.official_pipeline import run as run_ml_driven
            ledger = run_ml_driven(args.shipments, args.notes, calibrate=args.recalibrate)
    except Exception:
        logger.exception("pipeline failed")
        return 1
    elapsed = time.monotonic() - t0

    write_output_csv(ledger, args.output)
    write_evidence_ledger_csv(ledger, args.ledger)

    logger.info("done in %.2fs (mode=%s) -- output: %s, ledger: %s", elapsed, args.mode, args.output, args.ledger)
    return 0


if __name__ == "__main__":
    sys.exit(main())
